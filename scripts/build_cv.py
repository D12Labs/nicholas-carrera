#!/usr/bin/env python3
"""Build data/cv.js for the /cv page.

Merges the works inventory (CAREER/modular-cv/data/works.json, the single source for works)
with data/cv-extra.json (performances and releases from nico-profile that works.json does not
hold). Output is a plain script that sets window.CV_ROWS, so the page needs no fetch.

Usage:  python3 scripts/build_cv.py            (from projects/nico-site)
        python3 scripts/build_cv.py --validate (check only: sources exist, no em dashes, no gaps)
"""
import json
import re
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
REMAGEN = SITE.parent.parent
WORKS = REMAGEN / "CAREER" / "modular-cv" / "data" / "works.json"
EXTRA = SITE / "data" / "cv-extra.json"
OUT = SITE / "data" / "cv.js"

TYPE = {
    "music": "Music", "video": "Video", "art": "Art", "code": "Software",
    "ux": "UX", "creative-tech": "Creative tech", "product": "Product",
    "events": "Events", "research": "Research",
}
EM_DASH = "\u2014"


def year_key(y: str) -> int:
    # latest date in the cell as YYYYMM (MM-YYYY or a bare year, which sorts after its months)
    keys = [int(yr) * 100 + int(mm or 13) for mm, yr in re.findall(r"(?:(\d{2})-)?(\d{4})", y)]
    if y.endswith("present"):
        return 999999  # ongoing work sorts first
    return max(keys) if keys else 0


def rows() -> list[dict]:
    works = json.loads(WORKS.read_text())["works"]
    extra = json.loads(EXTRA.read_text())
    skip = set(extra.get("exclude", {}))
    roles = extra.get("role_override", {})
    dates = extra.get("dates", {})
    out = []
    for w in works:
        if w["id"] in skip:
            continue
        year = str(w.get("year", "")).replace("-", " to ")
        role = roles.get(w["id"], w.get("role", ""))
        out.append({"title": w["title"], "year": year, "type": TYPE.get(w["category"], w["category"].title()), "role": role})
    out += extra["rows"]
    for r in out:
        r["year"] = dates.get(r["title"], r["year"])
    # newest first; undated rows last; stable within a year
    return sorted(out, key=lambda r: -year_key(r["year"]) if r["year"] else 1)


def validate(rs: list[dict]) -> list[str]:
    errs = []
    for r in rs:
        for k in ("title", "type", "role"):
            if not r.get(k):
                errs.append(f"missing {k}: {r}")
        if not re.fullmatch(r"\d{2}-\d{4}( to (\d{2}-\d{4}|present))?", r.get("year", "")):
            errs.append(f"no MM-YYYY date: {r['title']} ({r.get('year')})")
        if any(EM_DASH in str(v) for v in r.values()):
            errs.append(f"em dash: {r['title']}")
    return errs


def main() -> int:
    for p in (WORKS, EXTRA):
        if not p.exists():
            print(f"missing source: {p}", file=sys.stderr)
            return 1
    rs = rows()
    errs = validate(rs)
    if errs:
        print("\n".join(errs), file=sys.stderr)
        return 1
    if "--validate" in sys.argv:
        print(f"ok: {len(rs)} rows")
        return 0
    OUT.write_text(
        "// Generated by scripts/build_cv.py from works.json + data/cv-extra.json. Do not edit by hand.\n"
        f"window.CV_ROWS = {json.dumps(rs, ensure_ascii=False, indent=1)};\n"
    )
    print(f"wrote {OUT.relative_to(SITE)}: {len(rs)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
