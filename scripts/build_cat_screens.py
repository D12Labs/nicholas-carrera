"""Convert every CAT SSO flow screen to WebP and write data/cat-screens.js (window.CAT_SCREENS).

Usage: python3 scripts/build_cat_screens.py <cat-x-depaul-sso-flows checkout>
Screens come from the team's flow viewer (manifest.json order). Exact duplicates
(the idle screen opens most flows) are kept once.
"""
import hashlib, json, pathlib, subprocess, sys

SRC = pathlib.Path(sys.argv[1]).resolve()
SITE = pathlib.Path(__file__).resolve().parent.parent
OUT = SITE / "public/media/caterpillar/screens"
OUT.mkdir(parents=True, exist_ok=True)

manifest = json.loads((SRC / "manifest.json").read_text())
seen, rows = set(), []
for flow in manifest["flows"]:
    for fr in flow["frames"]:
        png = SRC / "assets/flows" / flow["id"] / fr["file"]
        digest = hashlib.md5(png.read_bytes()).hexdigest()
        if digest in seen:
            continue
        seen.add(digest)
        name = f'{flow["id"][:2]}-{pathlib.Path(fr["file"]).stem}.webp'
        subprocess.run(["cwebp", "-quiet", "-q", "84", str(png), "-o", str(OUT / name)], check=True)
        w, h = (int(x) for x in subprocess.run(
            ["sips", "-g", "pixelWidth", "-g", "pixelHeight", str(png)],
            capture_output=True, text=True, check=True).stdout.split()[-3::2])
        rows.append({"type": "image", "src": f"public/media/caterpillar/screens/{name}",
                     "w": w, "h": h, "round": True, "caption": f'{flow["title"]} · {fr["label"]}'})

js = ("// Generated by scripts/build_cat_screens.py from the team's flow viewer. Do not edit by hand.\n"
      "window.CAT_SCREENS = " + json.dumps(rows, indent=1, ensure_ascii=False) + ";\n")
(SITE / "data/cat-screens.js").write_text(js)
print(f"{len(rows)} screens")
